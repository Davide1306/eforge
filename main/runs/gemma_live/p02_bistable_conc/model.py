def make_z_mesh(Nz, Z_max, alpha=3.0):
    """tanh-stretched z mesh on [0, Z_max], refined at z=0; shape (Nz+1,)."""
    i = np.arange(Nz + 1, dtype=float)
    return Z_max * (1.0 - np.tanh(alpha * (Nz - i) / Nz) / np.tanh(alpha))


def sigma_GC(psi_0, c_b, eps_r=EPS_R, temp=T):
    """Chapman-Grahame diffuse-layer charge [C/m^2]."""
    return np.sqrt(8.0 * EPS0 * eps_r * R * temp * c_b) * np.sinh(
        F * psi_0 / (2.0 * R * temp))


def solve_psi0(E_M, E_pzc, C_H, c_b, eps_r=EPS_R, temp=T):
    """Solve sigma_GC(psi_0) = C_H (E_M - E_pzc - psi_0) for psi_0 [V]."""
    def f(psi):
        return sigma_GC(psi, c_b, eps_r, temp) - C_H * (E_M - E_pzc - psi)
    return brentq(f, -3.0, 3.0, xtol=1e-12, rtol=1e-12)


def residual_2d(phi_flat, p):
    """Dimensionless 2-D PB residual, shape (Ny*Nz,). Pure numpy."""
    Ny, Nz = p['Ny'], p['Nz']
    zeta, deta, nu, Phi = p['zeta'], p['deta'], p['nu'], p['Phi']

    phi = phi_flat.reshape(Ny, Nz)
    phi_aug = np.concatenate([phi, np.zeros((Ny, 1))], axis=1)  # Dirichlet k=Nz

    # Robin BC at k=0, second-order one-sided stencil
    h0 = zeta[1] - zeta[0]
    h1 = zeta[2] - zeta[1]
    cn = h0 + h1
    dphi_dz_0 = (cn**2 * phi_aug[:, 1] - h0**2 * phi_aug[:, 2]
                 - h1 * (2.0 * h0 + h1) * phi_aug[:, 0]) / (h0 * h1 * cn)
    R_bc = dphi_dz_0 - nu * (phi_aug[:, 0] - Phi)

    # Interior 5-point PB at k=1..Nz-1
    h_m = zeta[1:-1] - zeta[:-2]
    h_p = zeta[2:] - zeta[1:-1]
    phi_c = phi_aug[:, 1:-1]
    d2z = (2.0 / (h_m + h_p)) * ((phi_aug[:, 2:] - phi_c) / h_p
                                 - (phi_c - phi_aug[:, :-2]) / h_m)
    d2y = (np.roll(phi_c, -1, axis=0) - 2.0 * phi_c
           + np.roll(phi_c, 1, axis=0)) / (p['deta'] * p['deta'])
    R_int = d2z + d2y - np.sinh(phi_c)

    return np.concatenate([R_bc[:, None], R_int], axis=1).ravel()


def build_jac_csr(phi_flat, p):
    """Analytical sparse CSR Jacobian of residual_2d (<=5 nnz/row)."""
    Ny, Nz = int(p['Ny']), int(p['Nz'])
    zeta, deta, nu = p['zeta'], float(p['deta']), p['nu']

    phi = phi_flat.reshape(Ny, Nz)
    inv_deta2 = 1.0 / (deta * deta)
    h0 = zeta[1] - zeta[0]
    h1 = zeta[2] - zeta[1]
    cn = h0 + h1
    h_m = zeta[1:-1] - zeta[:-2]
    h_p = zeta[2:] - zeta[1:-1]
    inv_hm, inv_hp = 1.0 / h_m, 1.0 / h_p
    c2 = 2.0 / (h_m + h_p)

    max_nnz = 3 * Ny + 5 * Ny * (Nz - 1)
    rows = np.empty(max_nnz, dtype=np.int32)
    cols = np.empty(max_nnz, dtype=np.int32)
    data = np.empty(max_nnz, dtype=np.float64)
    ptr = 0

    dbc0 = -h1 * (2 * h0 + h1) / (h0 * h1 * cn) - nu
    dbc1 = cn / (h0 * h1)
    dbc2 = -h0 / (h1 * cn)
    for i in range(Ny):
        r = i * Nz
        rows[ptr] = r; cols[ptr] = r;     data[ptr] = dbc0[i]; ptr += 1
        rows[ptr] = r; cols[ptr] = r + 1; data[ptr] = dbc1;    ptr += 1
        rows[ptr] = r; cols[ptr] = r + 2; data[ptr] = dbc2;    ptr += 1

    for i in range(Ny):
        il, ir = (i - 1) % Ny, (i + 1) % Ny
        for j in range(Nz - 1):
            k = j + 1
            r = i * Nz + k
            ctr = c2[j] * (-inv_hp[j] - inv_hm[j]) - 2 * inv_deta2 - np.cosh(phi[i, k])
            rows[ptr] = r; cols[ptr] = r;             data[ptr] = ctr; ptr += 1
            rows[ptr] = r; cols[ptr] = r - 1;         data[ptr] = c2[j] * inv_hm[j]; ptr += 1
            if k < Nz - 1:
                rows[ptr] = r; cols[ptr] = r + 1;     data[ptr] = c2[j] * inv_hp[j]; ptr += 1
            rows[ptr] = r; cols[ptr] = il * Nz + k;   data[ptr] = inv_deta2; ptr += 1
            rows[ptr] = r; cols[ptr] = ir * Nz + k;   data[ptr] = inv_deta2; ptr += 1

    N = Ny * Nz
    return coo_matrix((data[:ptr], (rows[:ptr], cols[:ptr])), shape=(N, N)).tocsr()


def solve_pb_2d(case, mesh):
    """Damped sparse-Newton solve. Returns (phi_yz, sigma_M, sigma_bar, result)."""
    E_M = float(case['E_M'])
    E_pzc = np.asarray(case['E_pzc'], dtype=float)
    C_H = np.asarray(case['C_H'], dtype=float)
    x = float(case['x'])
    c_b = float(case['c_b'])
