    z = make_z_mesh(Nz, Z_max, alpha=3.0)

    zeta = z / lambda_D
    deta = (L / Ny) / lambda_D
    facet = np.where(y < x * L, 0, 1)
    nu = C_H[facet] * lambda_D / (EPS0 * EPS_R)
    Phi = F * (E_M - E_pzc[facet]) / (R * T)
    p = {'Ny': Ny, 'Nz': Nz, 'zeta': zeta, 'deta': deta, 'nu': nu, 'Phi': Phi}

    # Initial guess: analytical GC profile per y-strip
    phi_init = np.zeros((Ny, Nz))
    for i in range(Ny):
        try:
            psi_0_i = solve_psi0(E_M, E_pzc[facet[i]], C_H[facet[i]], c_b)
        except Exception:
            psi_0_i = 0.0
        phi0_i = F * psi_0_i / (R * T)
        gamma_i = np.tanh(phi0_i / 4.0)
        arg = np.clip(gamma_i * np.exp(-zeta[:Nz]), -1.0 + 1e-12, 1.0 - 1e-12)
        phi_init[i, :] = 4.0 * np.arctanh(arg)

    # Damped Newton with sparse analytical Jacobian (port of GC 'sparse' path)
    x_s = phi_init.ravel().copy()
    f_s = residual_2d(x_s, p)
    converged = False
    fn_prev = float('inf')
    stag = 0
    for _ in range(50):
        fn = float(np.linalg.norm(f_s))
        if fn < 1e-8:
            converged = True
            break
        if fn_prev > 0 and abs(fn - fn_prev) / fn_prev < 1e-3:
            stag += 1
            if stag >= 3:
                break
        else:
            stag = 0
        fn_prev = fn
        J = build_jac_csr(x_s, p)
        dx = spsolve(J, -f_s)
        alpha = 1.0
        fn2 = fn * fn
        f_try = f_s
        for __ in range(30):
            f_try = residual_2d(x_s + alpha * dx, p)
            if float(np.dot(f_try, f_try)) < fn2 * (1.0 - 1e-4 * alpha):
                break
            alpha *= 0.5
        x_s = x_s + alpha * dx
        f_s = f_try
    fn_final = float(np.linalg.norm(f_s))
    success = converged or (fn_final < 1e-6)
    result = OptimizeResult(x=x_s, fun=f_s, success=success,
                            message='Converged' if success else 'Max iterations reached')

    phi_d_full = np.concatenate([result.x.reshape(Ny, Nz), np.zeros((Ny, 1))], axis=1)
    phi_yz = phi_d_full * (R * T / F)
    psi_surf = phi_yz[:, 0]
    sigma_M = C_H[facet] * (E_M - E_pzc[facet] - psi_surf)
    sigma_bar = float(np.mean(sigma_M))
    return phi_yz, sigma_M, sigma_bar, result


