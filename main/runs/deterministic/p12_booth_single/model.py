# Overflow guard for the dimensionless exponent (see polyc physics.py rationale).
_EXP_CLAMP = 200.0


def _bphi(phi):
    return np.clip(beta * e_0 * np.asarray(phi, dtype=float), -_EXP_CLAMP, _EXP_CLAMP)


def sinhc(u):
    """sinh(u)/u, with a small-u series (-> 1 at u = 0)."""
    u = np.clip(np.asarray(u, dtype=float), -_EXP_CLAMP, _EXP_CLAMP)
    scalar = (u.ndim == 0)
    u = np.atleast_1d(u)
    out = np.empty_like(u)
    small = np.abs(u) < 1e-4
    us = u[small]
    out[small] = 1.0 + us**2 / 6.0 + us**4 / 120.0
    ub = u[~small]
    out[~small] = np.sinh(ub) / ub
    return float(out[0]) if scalar else out


def langevin_L(u):
    """Langevin function L(u) = coth(u) - 1/u, with small-u series (-> u/3)."""
    u = np.asarray(u, dtype=float)
    scalar = (u.ndim == 0)
    u = np.atleast_1d(u)
    out = np.empty_like(u)
    small = np.abs(u) < 1e-4
    us = u[small]
    out[small] = us / 3.0 - us**3 / 45.0
    ub = u[~small]
    out[~small] = 1.0 / np.tanh(ub) - 1.0 / ub
    return float(out[0]) if scalar else out


def langevin_Lc(u):
    """L(u)/u, smooth at u = 0 (-> 1/3). Used by eps_eff so the E -> 0 limit needs
    no division by the field."""
    u = np.asarray(u, dtype=float)
    scalar = (u.ndim == 0)
    u = np.atleast_1d(u)
    out = np.empty_like(u)
    small = np.abs(u) < 1e-3
    us = u[small]
    out[small] = 1.0 / 3.0 - us**2 / 45.0 + 2.0 * us**4 / 945.0
    ub = u[~small]
    out[~small] = (1.0 / np.tanh(ub) - 1.0 / ub) / ub
    return float(out[0]) if scalar else out


def denominator_D(phi, E, v):
    """eq 2 shared denominator D(phi, E):
        D = (v/2)(g+ e^{-b e0 phi} + g- e^{+b e0 phi})
            + [1 - (v/2)(g+ + g-)] * sinh(bpE)/(bpE).
    Note D(0,0) = 1 for any v."""
    bphi = _bphi(phi)
    S = sinhc(beta * P_DIP * np.asarray(E, dtype=float))
    return (v / 2.0) * (gamma_p * np.exp(-bphi) + gamma_m * np.exp(bphi)) \
        + (1.0 - (v / 2.0) * (gamma_p + gamma_m)) * S


def number_densities(phi, E, n_b, v):
    """eq 2: n_+- = n_b e^{-+ b e0 phi} / D. Returns (n_plus, n_minus)."""
    bphi = _bphi(phi)
    D = denominator_D(phi, E, v)
    return n_b * np.exp(-bphi) / D, n_b * np.exp(bphi) / D


def n_water(phi, E, v):
    """eq 4 (E1 fix D_4 == D): n_w = n_w^b * [sinh(bpE)/(bpE)] / D."""
    S = sinhc(beta * P_DIP * np.asarray(E, dtype=float))
    return n_w_b * S / denominator_D(phi, E, v)


def eps_eff(phi, E, v):
    """eq 3: eps_eff = eps_opt + (n_w p / E) L(bpE)
            = eps_opt + n_w beta p^2 Lc(bpE)   (Lc = L/u, smooth at E = 0).
    Low-field limit eps_eff(0,0) = eps_S exactly."""
    u = beta * P_DIP * np.asarray(E, dtype=float)
    return eps_opt + n_water(phi, E, v) * beta * P_DIP**2 * langevin_Lc(u)


# ── pb1d.py (1-D modified PB solver + analytic helpers; eqs 1,5,6,10,11) ──
def make_grid(lam_D, n=257, z_max_over_lamD=25.0, stretch=7.0):
    """Nonuniform z grid [m], length n, clustered at the wall (z=0)."""
    s = np.linspace(0.0, 1.0, n)
    return z_max_over_lamD * lam_D * (np.exp(stretch * s) - 1.0) / (np.exp(stretch) - 1.0)


def _control_volumes(z):
    h = np.diff(z)
    w = np.empty(z.size)
    w[0] = h[0] / 2.0
    w[-1] = h[-1] / 2.0
    w[1:-1] = 0.5 * (h[:-1] + h[1:])
    return h, w


def _charge_density(phi, E_node, n_b, v):
    """rho = e_0 (n_+ - n_-)  [C/m^3]."""
    n_plus, n_minus = number_densities(phi, E_node, n_b, v)
    return e_0 * (n_plus - n_minus)


def _assemble(phi, z, h, n_b, v):
    """Face fluxes J [length n-1], node field E_node, charge density rho."""
    dphi = np.diff(phi)
    phi_f = 0.5 * (phi[:-1] + phi[1:])
    E_f = np.abs(dphi / h)
    eps_f = eps_eff(phi_f, E_f, v)
    J = eps_f * dphi / h
    E_node = np.empty(z.size)
    E_node[1:-1] = 0.5 * (E_f[:-1] + E_f[1:])
    E_node[0] = E_f[0]
    E_node[-1] = E_f[-1]
    rho = _charge_density(phi, E_node, n_b, v)
    return J, rho


def _residual_dirichlet(phi_int, psi_0, z, h, w, n_b, v):
    phi = np.empty(z.size)
    phi[0] = psi_0
    phi[-1] = 0.0
    phi[1:-1] = phi_int
    J, rho = _assemble(phi, z, h, n_b, v)
    # interior nodes 1..N-1:  J_{i+1/2} - J_{i-1/2} + rho_i w_i = 0
    return (J[1:] - J[:-1]) + rho[1:-1] * w[1:-1]


def solve_dirichlet(psi_0, c_b_M, n=257, z_max_over_lamD=25.0, stretch=7.0,
                    phi_guess=None):
    """Solve the diffuse layer for a fixed wall potential psi_0 [V]."""
    lam = lambda_D(c_b_M)
    z = make_grid(lam, n, z_max_over_lamD, stretch)
    h, w = _control_volumes(z)
    n_b, v = n_b_local(c_b_M), v_frac(c_b_M)
    if phi_guess is None:
        phi_guess = psi_0 * np.exp(-z / lam)
    sol = root(_residual_dirichlet, np.asarray(phi_guess)[1:-1],
               args=(psi_0, z, h, w, n_b, v), method="hybr")
    phi = np.empty(z.size)
    phi[0] = psi_0
    phi[-1] = 0.0
    phi[1:-1] = sol.x
    R = _residual_dirichlet(sol.x, psi_0, z, h, w, n_b, v)
    J, rho = _assemble(phi, z, h, n_b, v)
    res_inf = float(np.linalg.norm(R, np.inf))
    res_rel = res_inf / (float(np.max(np.abs(J))) + 1e-300)
    sigma_M = float(-np.sum(rho * w))   # sigma_M = -Q_diff (Gauss + neutrality)
    return dict(z=z, phi=phi, success=bool(sol.success), res_inf=res_inf,
                res_rel=res_rel, sigma_M=sigma_M, lam_D=lam, v=v, n_b=n_b)


def diffuse_capacitance(psi_0, c_b_M, dpsi=5e-4, **kw):
    """C_diff = d sigma_M / d psi_0  [F/m^2] by central difference (warm-started)."""
    sp_ = solve_dirichlet(psi_0 + dpsi, c_b_M, **kw)
    sm = solve_dirichlet(psi_0 - dpsi, c_b_M, **kw)
    return (sp_["sigma_M"] - sm["sigma_M"]) / (2.0 * dpsi)


def C_GC_min(c_b_M):
    """Analytic Gouy-Chapman differential-capacitance minimum eps_S/lambda_D."""
    return eps_S / lambda_D(c_b_M)


