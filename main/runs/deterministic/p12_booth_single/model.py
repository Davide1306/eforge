    out['C_dl_uFcm2'] = [float(SI_to_uFcm2(v)) for v in Cf]    # display view [uF/cm^2]
    out['minima'] = [[float(em), float(cm)] for (em, cm) in minima]     # SI [(E_V, C_Fm2)]
    out['minima_uFcm2'] = [[float(em), float(SI_to_uFcm2(cm))] for (em, cm) in minima]
    out['n_minima'] = int(len(minima))
